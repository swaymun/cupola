#!/usr/bin/env python3
"""Regenerates the A-DUO-FOLDED capture scenarios (same states for every theme and posture)."""
from pathlib import Path

BASE = ("--fixture subagent-fixture --fixture chat-layout --fixture chat-layout-unsaved "
        "--fixture project-actions --fixture project-speed --fixture send-states "
        "--fixture several-computers")
THEMES = ["cupola-light", "cupola-dark", "nord", "misty-forest"]
OUT = Path(__file__).parent / "scenarios"


def block(tag, theme, display=""):
    chk = "check-layout folded\n" if tag == "folded" else ""
    d = f" --display {display}" if display else ""
    t = f"--fixture theme --arg {theme}"
    n = f"a-duo-folded-{tag}-{theme}"
    return f"""# {tag} / {theme}
driver on
launch {BASE} --fixture open-project-thread {t}
driver off
wait --id message-draft --timeout 30
wait --id conversation-loading --gone --timeout 15
tree --json
{chk}shot {n}-bottom{d}
driver on
launch {BASE} --fixture open-project-thread {t} --arg=-diagnostics-scroll-top
driver off
wait --id scroll-to-bottom --timeout 20
tree --json
{chk}shot {n}-scrolled{d}
tap --id message-draft
type "A two-line draft that is long enough to wrap onto a second line in a narrow folded pane."
tree --json
shot {n}-keyboard{d}
driver on
launch {BASE} --fixture fresh-agent-defaults {t}
driver off
wait --id new-chat-access --timeout 30
tree --json
{chk}shot {n}-newchat{d}
"""


def write(name, header, blocks):
    (OUT / name).write_text(header + "\n".join(blocks))


write("a-duo-folded-captures.wctl", "# devices: iphone ipad\n# Generated by control/gen-folded-captures.py\n",
      [block("std", th) for th in THEMES])
duo = []
for th in THEMES:
    duo.append("hinge 0\norient portrait\n" + block("folded", th))
for th in THEMES:
    duo.append("hinge 180\norient portrait\n" + block("unfolded", th, "primary-1"))
duo.append("hinge 0\norient portrait\n")
write("a-duo-folded-captures-duo.wctl", "# devices: duo\n# Generated by control/gen-folded-captures.py\n", duo)
