#!/usr/bin/env python3
"""Writes the UX-DUO-3 capture scenarios (iPhone/iPad and Duo) so every state is launched the same way.

States that need a real tap (reveal, long-press) live in ux-duo-3-behavior.wctl, which is written by hand.
Run: python3 apps/ios/control/gen-ux-duo-3-captures.py
"""
from pathlib import Path

BASE = "--fixture subagent-fixture --fixture chat-layout --fixture chat-layout-unsaved --fixture project-actions"
NEW = BASE + " --fixture project-speed --fixture send-states --fixture several-computers --fixture fresh-agent-defaults"
# name, launch flags, element that proves the screen, whether the unit's "before" build can reach it
STATES = [
    ("newchat", NEW + " --fixture offline-studio", "new-chat-access"),
    ("newchat-offline", NEW + " --fixture offline-all", "new-chat-access"),
    ("newchat-computers", NEW + " --fixture offline-studio --fixture new-chat-computers-open", "connection-options"),
    ("newchat-projects", NEW + " --fixture offline-studio --fixture new-chat-projects-open", "project-options"),
    ("automations-offline", BASE + " --fixture several-computers --fixture offline-studio --fixture automations-open", "automations-offline"),
]
THEMES = ["cupola-light", "cupola-dark"]
HERE = Path(__file__).parent / "scenarios"


def body(device, display=None):
    shot_suffix = f" --display {display}" if display else ""
    lines = []
    for theme in THEMES:
        for name, flags, ready in STATES:
            lines += [f"launch {flags} --fixture theme --arg {theme}",
                      f"wait --id {ready} --timeout 30",
                      f"shot ux-duo-3-{device}-{name}-{theme.split('-')[1]}{shot_suffix}", ""]
    return lines


def write(name, header, lines):
    (HERE / name).write_text("\n".join(header + lines) + "\n")


write("ux-duo-3-captures.wctl",
      ["# devices: iphone ipad",
       "# UX-DUO-3: offline computers stay quiet, one picker row shape, no View computer / Files pills. Offline fixtures; nothing is sent.",
       "# Generated by control/gen-ux-duo-3-captures.py; Settings, Usage and Connection details are previewed (control/fixtures/ux-duo-3-preview.json)."],
      body("phone"))
write("ux-duo-3-captures-duo.wctl",
      ["# devices: duo",
       "# UX-DUO-3 on the Duo: folded cover, then unfolded inner display. Duo taps are gated (#387), so every state opens by launch flag.",
       "# Generated by control/gen-ux-duo-3-captures.py.",
       "hinge 180", "hinge 0", "orient portrait", ""],
      body("duo-folded") + ["hinge 180", ""] + body("duo-unfolded", "primary-1"))
